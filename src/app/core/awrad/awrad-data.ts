export function getNextDhikr(currentId: string): DhikrItem {
  const idx = DEFAULT_DHIKR_SEQUENCE.findIndex((d) => d.id === currentId);
  const nextIdx = (idx + 1) % DEFAULT_DHIKR_SEQUENCE.length;
  return DEFAULT_DHIKR_SEQUENCE[nextIdx];
}

/** Calculate SVG circular stroke dasharray for progress */
export function calcDashArray(count: number, target: number, radius: number): string {
  const circumference = 2 * Math.PI * radius;
  const ratio = Math.max(0, Math.min(1, count / target));
  const dash = (circumference * ratio).toFixed(1);
  return `${dash} ${circumference.toFixed(1)}`;
}

